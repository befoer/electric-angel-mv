export const REV = { ...DEFAULT };
export const rev = k => {
  if (!(k in REV)) throw new Error(`rev：没有这个开关 ${k}（删旧开关时漏改了调用处？）`);
  return REV[k];
};

// 'opening=8,comfy=8'（逗号或空格分隔，= 或 : 都行）
export function setRev(spec) {
  if (!spec) return;
  for (const kv of String(spec).split(/[,;\s]+/)) {
    if (!kv) continue;
    const [k, v] = kv.split(/[=:]/);
    if (k in REV) REV[k] = +v;
    else console.warn(`rev：没有这个开关 ${k}（可用：${Object.keys(REV).join(' ')}）`);
  }
}
