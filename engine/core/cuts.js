export function cutShift(b) { // 这个切点因为实测要挪多少秒（0 = 不挪）
  const id = BAR_LINE[b], m = id && D.onsets?.[id]?.[0]; // 数据还没加载（模块初始化时）就不挪
  if (m == null || b in CUT17) return 0;
  const d = m - rawLyric(id).chars[0].t0;
  return Math.abs(d) > 0.06 ? d : 0;
}
// 不挪时的切点（调试面板对比用）
export function cutAtOld(b) {
  if (b in CUT17) return CUT17[b];
  if (b in CUT16) return CUT16[b];
  if (b in CUT15) return CUT15[b];
  return barStart(b);
}
